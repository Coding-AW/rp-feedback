/**
 * @brief Droop-correction filter (block 3) for the acquisition system.
 *        One channel; instantiate twice, once for I and once for Q.
 *
 * @Author Alex (Imperial CCM internship) - custom module
 *
 * (c) Red Pitaya  http://www.redpitaya.com  (baseline v0.94)
 *
 * Part of the acquisition system of Herkenhoff et al., Rev. Sci. Instrum. 92,
 * 103201 (2021).  Fig. 6a, the two blocks labelled "FIR".
 *
 * ===========================================================================
 *  WHAT THIS BLOCK IS FOR
 * ===========================================================================
 *  The decimator averages, and averaging is not even-handed: a signal at the
 *  centre of the measurement window passes at full strength, one near the edge
 *  comes out weaker. That sag is called passband droop, and it is a real
 *  distortion - the same ion signal would appear smaller simply for sitting
 *  further from the local oscillator.
 *
 *  Nothing is lost, though. The sag is a fixed, known shape, so a second filter
 *  with exactly the opposite shape cancels it. That is this block.
 *
 *  Measured effect of the correction (from gen_fir_coeffs.py):
 *
 *      uncorrected droop at the band edge : -2.317 dB
 *      after correction                   :  0.036 dB peak-to-peak, whole band
 *
 *  and identical at every decimation factor from 256 to 4096, because in units
 *  of the OUTPUT sample rate the droop shape barely changes with R. That is why
 *  one fixed set of coefficients serves them all.
 *
 * ===========================================================================
 *  HOW 309 TAPS FIT IN ONE MULTIPLIER
 * ===========================================================================
 *  A filter of this kind computes, for each output sample,
 *
 *      y[n] = sum over k of  h[k] * x[n-k]           k = 0 .. 308
 *
 *  Done literally that needs 309 multipliers. The chip has 80. Two properties
 *  rescue it:
 *
 *  1. THERE IS TIME. This filter runs at the DECIMATED rate, so between one
 *     output sample and the next there are R clock cycles - at least 256. One
 *     multiplier used 155 times is far cheaper than 155 multipliers used once.
 *
 *  2. THE FILTER IS SYMMETRIC: h[k] = h[308-k]. So each coefficient serves two
 *     taps, and instead of two multiplies we ADD the two samples first and
 *     multiply once:
 *
 *         h[k]*x[n-k] + h[308-k]*x[n-308+k]  =  h[k] * ( x[n-k] + x[n-308+k] )
 *
 *     That halves the work to 155 multiplies, and halves the coefficient
 *     storage too. Reading two samples at once is free: block RAM has two
 *     independent read ports.
 *
 *  So: one multiplier, 155 clock cycles, one output sample.
 *
 * ===========================================================================
 *  THE MINIMUM DECIMATION FACTOR  -  IMPORTANT
 * ===========================================================================
 *  155 cycles of work per output sample means the input samples must be at
 *  least ~160 cycles apart. Decimation R = 256 and above is fine. R = 64 and
 *  R = 128 are NOT: the next sample would arrive before this one finished.
 *
 *  The module does not fail silently if that happens. A new input while still
 *  working restarts the calculation and sets the sticky `overrun_o` flag, and
 *  the parent module (red_pitaya_acq) bypasses this filter entirely below
 *  R = 256. So the usable settings are:
 *
 *      R =   64, 128        correction unavailable, filter bypassed
 *      R =  256 .. 4096     correction active
 *
 *  If you ever need correction at R = 64, the fix is fewer taps: NTAPS = 127
 *  would need 64 cycles. Re-run gen_fir_coeffs.py with NTAPS changed and
 *  update the parameter here to match.
 *
 * ===========================================================================
 *  COEFFICIENTS
 * ===========================================================================
 *  Held in fir_coeffs.vh, GENERATED by acquisition_custom/gen_fir_coeffs.py.
 *  Do not hand-edit that file - re-run the script. It sits in this directory so
 *  the include below resolves without an include-path setting.
 *
 *  Only the unique half is stored: taps 0..154. Tap 155..308 mirror them.
 *
 *  They are 18-bit signed integers scaled by 2^17, so a coefficient of 1.0 is
 *  stored as 131072. The accumulated result is therefore 2^17 times too large
 *  and is shifted back down at the output. The generator forces the sum to be
 *  exactly 2^17, which makes the filter's gain at DC exactly 1 - so switching
 *  the correction on and off does not change the overall scale of the data.
 */

`timescale 1ns / 1ps

module red_pitaya_acq_fir #(
  parameter integer DW    = 32,   // data width in and out, signed
  parameter integer DEPTH = 512,  // sample history, power of two, >= NTAPS
  parameter integer ABW   = 9,    // address width, 2^ABW == DEPTH
  parameter integer ACCW  = 60    // accumulator width (see the note below)
)(
  // ---- clock and reset ----
  input                      clk_i    ,  //!< 125 MHz processing clock
  input                      rstn_i   ,  //!< active-LOW synchronous reset

  // ---- input: one sample per strobe, at the decimated rate ----
  input      signed [DW-1:0] dat_i    ,  //!< from the decimator
  input                      stb_i    ,  //!< 1 clock high when dat_i is new

  // ---- output ----
  output reg signed [DW-1:0] dat_o    ,  //!< corrected sample
  output reg                 stb_o    ,  //!< 1 clock high when dat_o is new

  // ---- status ----
  output reg                 overrun_o ,  //!< sticky: input arrived while busy

  // ---- software access to the coefficients ----
  //      Lets the filter be redesigned at run time, without rebuilding the
  //      bitstream. See the note below.
  input      [        8:0]   coef_addr_i ,  //!< which coefficient, 0 .. NHALF-1
  input      [       17:0]   coef_wdata_i,  //!< value to store
  input                      coef_we_i   ,  //!< 1 clock high to store it
  output     [       17:0]   coef_rdata_o   //!< value currently stored there
);

//---------------------------------------------------------------------------------
//  Sizes - taken from the GENERATED file, not written out again here.
//
//  NTAPS and the coefficient scaling appear in three places: this module, the
//  bypass decision in red_pitaya_acq.v, and validate_fir.py. Written by hand in
//  each, they drift apart eventually - and a mismatch does not fail loudly. It
//  produces a filter that builds, runs, and gives wrong answers.
//
//  So gen_fir_coeffs.py writes them once into fir_params.vh and everything
//  reads from there. To change the filter, edit ONLY that script and re-run it.
//---------------------------------------------------------------------------------
`include "fir_params.vh"

localparam integer NTAPS     = GEN_NTAPS;
localparam integer COEFW     = GEN_COEFW;
localparam integer COEF_FRAC = GEN_COEF_FRAC;
localparam integer NHALF     = GEN_NHALF;     // unique coefficients, 0 .. NHALF-1
localparam integer CENTRE    = NHALF - 1;     // the middle tap

//---------------------------------------------------------------------------------
//  Build-time check: the sample history must hold the whole filter.
//
//  If NTAPS is ever raised past DEPTH, the circular buffer would silently wrap
//  and the oldest taps would read the wrong samples - a filter that still runs
//  and still produces plausible numbers. This turns that into a build failure
//  with a name that says what to do.
//---------------------------------------------------------------------------------
generate
  if (DEPTH < NTAPS) begin : check_depth
    ERROR_fir_DEPTH_must_be_at_least_NTAPS_see_gen_fir_coeffs_output bad ();
  end
endgenerate

// Accumulator width check, for the record:
//   pre-add of two DW-bit samples : DW+1 = 33 bits
//   times a COEFW-bit coefficient : 33 + 18 = 51 bits
//   summed over 155 taps          : + 8 bits = 59 bits
// ACCW = 60 leaves a bit of margin. Widening it is free in a design with this
// much room; narrowing it would silently wrap on large signals.

//---------------------------------------------------------------------------------
//  Coefficient store
//
//  A small read-only memory holding the unique half of the filter. Filled at
//  elaboration time from the generated include file - no hardware is built for
//  the initial block itself, the values are baked into the memory contents.
//---------------------------------------------------------------------------------
//  WHY THIS IS A RAM AND NOT A ROM
//
//  The coefficients define what the filter does. Baked in at build time they can
//  only be changed by rebuilding the whole bitstream - about 25 minutes, on a PC
//  with Vivado installed, followed by reloading the board. That is a heavy price
//  for trying a slightly different passband.
//
//  Making the memory writable from software costs one extra port on a block RAM,
//  which is free (block RAM has two ports and the filter only needs one), and
//  changes nothing in the signal path. In exchange the filter can be redesigned
//  from a notebook in milliseconds.
//
//  It also makes the coefficients READABLE, which matters more than it sounds:
//  without readback there is no way to tell what the chip actually contains, only
//  what it was supposed to contain. Those are different things, and telling them
//  apart has already cost time on this project.
//
//  The initial contents still come from the generated file, so the board powers
//  up with the designed filter and software only needs to intervene to change it.
//
//  IMPORTANT: do not write coefficients while the filter is running. A pass takes
//  155 clocks and reads the memory throughout; changing it midway mixes two
//  different filters and produces a burst of nonsense. Disable the chain, write,
//  then re-enable - red_pitaya_acq's register interface makes that the natural
//  order.
(* ram_style = "block" *)
reg signed [COEFW-1:0] coef [0:NHALF-1];

initial begin
  `include "fir_coeffs.vh"
end

//  Software port. Separate from the filter's own read, so the two never contend:
//  block RAM genuinely has two independent ports.
reg signed [COEFW-1:0] coef_sw_rd;

always @(posedge clk_i) begin
  if (coef_we_i) coef[coef_addr_i[8:0]] <= coef_wdata_i[COEFW-1:0];
  coef_sw_rd <= coef[coef_addr_i[8:0]];
end

assign coef_rdata_o = {{(18-COEFW){coef_sw_rd[COEFW-1]}}, coef_sw_rd};

//---------------------------------------------------------------------------------
//  Sample history
//
//  A circular buffer. Rather than shifting 309 stored samples along every time a
//  new one arrives, the samples stay put and a write pointer moves. Because
//  DEPTH is a power of two, the pointer arithmetic wraps by itself.
//
//  Two independent read addresses are needed each cycle - one for each end of a
//  symmetric tap pair - which is exactly what block RAM's two ports provide.
//---------------------------------------------------------------------------------
reg signed [DW-1:0]  dbuf [0:DEPTH-1];
reg        [ABW-1:0] wp;        // where the next sample goes
reg        [ABW-1:0] wp_snap;   // wp at the moment this output sample started

//---------------------------------------------------------------------------------
//  Control: one pass of 155 multiply-accumulates per input sample
//---------------------------------------------------------------------------------
reg [ABW-1:0] k;       // which coefficient we are on, 0 .. NHALF-1
reg           busy;

wire issue     = busy;                       // a tap is being fetched this cycle
wire last_tap  = busy && (k == CENTRE[ABW-1:0]);

always @(posedge clk_i) begin
  if (rstn_i == 1'b0) begin
    wp      <= {ABW{1'b0}};
    wp_snap <= {ABW{1'b0}};
    k       <= {ABW{1'b0}};
    busy    <= 1'b0;
    overrun_o <= 1'b0;
  end else begin
    if (stb_i) begin
      // Store the new sample and start a fresh pass. Reads begin next cycle, by
      // which time this write has landed.
      dbuf[wp] <= dat_i;
      wp_snap  <= wp;
      wp       <= wp + 1'b1;
      k        <= {ABW{1'b0}};
      busy     <= 1'b1;
      // Arriving while still working means the decimation factor is too small
      // for a filter this long. Restart rather than emit a half-finished
      // result, and latch the fact so software can see it.
      if (busy) overrun_o <= 1'b1;
    end else if (busy) begin
      if (last_tap) busy <= 1'b0;
      else          k    <= k + 1'b1;
    end
  end
end

//---------------------------------------------------------------------------------
//  Stage 1 - fetch the symmetric pair and its shared coefficient
//
//  Tap k        is the sample k steps back      -> wp_snap - k
//  Tap NTAPS-1-k is that many steps back        -> wp_snap - (NTAPS-1) + k
//
//  At the centre tap those two addresses coincide. Adding the sample to itself
//  would double the middle coefficient's contribution, so the pre-add is
//  suppressed there - see `is_centre` below.
//---------------------------------------------------------------------------------
wire [ABW-1:0] addr_a = wp_snap - k;
wire [ABW-1:0] addr_b = wp_snap - (NTAPS-1) + k;

reg signed [DW-1:0]    rd_a, rd_b;
reg signed [COEFW-1:0] coef_r;
reg                    is_centre_1;

always @(posedge clk_i) begin
  rd_a        <= dbuf[addr_a];
  rd_b        <= dbuf[addr_b];
  coef_r      <= coef[k];
  is_centre_1 <= (k == CENTRE[ABW-1:0]);
end

//---------------------------------------------------------------------------------
//  Stage 2 - pre-add the pair (the trick that halves the multiplies)
//
//  ===========================================================================
//   WRITTEN AS if/else RATHER THAN ?: - AND THAT IS NOT A MATTER OF TASTE.
//   DO NOT "TIDY" THIS BACK INTO A CONDITIONAL EXPRESSION.
//  ===========================================================================
//
//  This block used to read:
//
//      pair <= is_centre_1 ? {rd_a[DW-1], rd_a} : (rd_a + rd_b);
//
//  which is wrong, silently, and only for some inputs. Here is why.
//
//  In Verilog a CONCATENATION - anything inside { } - is always UNSIGNED, no
//  matter what is put in it. And in any expression, if one part is unsigned the
//  WHOLE expression becomes unsigned, and every operand in it is then extended
//  with zeros instead of with its sign bit.
//
//  So the braces on the left-hand branch reached across the colon and turned
//  `rd_a + rd_b` into an unsigned addition. Two negative samples still came out
//  right, by luck: each is zero-extended by adding 2^32, and the two extra
//  2^32s add up to 2^33, which falls off the top of a 33-bit result and
//  vanishes. Two positive samples were right too, having nothing to extend.
//
//  But ONE POSITIVE AND ONE NEGATIVE left a single 2^32 behind, and 2^32 is
//  every bit of a 33-bit number. That one tap pair then contributed an error of
//  about 2^32 to the sum - roughly a hundred thousand times a normal sample -
//  and the output slammed into its limit.
//
//  Why it hid for so long: at the centre of the measurement window the signal
//  barely moves, every sample in the filter's memory has the same sign, and the
//  filter is correct. Move off centre and the signal changes sign within the
//  window; the further off, the more tap pairs straddle zero, and the worse it
//  gets. It therefore looked exactly like a filter with the wrong shape rather
//  than like a fault.
//
//  The fix is to keep the braces out of the arithmetic entirely. A plain
//  assignment from a signed value to a wider signed target sign-extends by
//  itself - no concatenation needed - and with the braces gone, the addition is
//  signed as intended.
//---------------------------------------------------------------------------------
reg signed [DW:0]      pair;      // DW+1 bits: the sum of two DW-bit numbers
reg signed [COEFW-1:0] coef_p;

always @(posedge clk_i) begin
  if (is_centre_1) pair <= rd_a;            // centre tap: use it once only.
                                            // signed -> wider signed: sign-extends
  else             pair <= rd_a + rd_b;     // everything else: pair them.
                                            // both signed, so the sum is signed
  coef_p <= coef_r;
end

//---------------------------------------------------------------------------------
//  Stage 3 - the single multiply
//
//  33 x 18 bits is wider than one DSP48E1 slice (25 x 18), so Vivado builds it
//  from two, automatically. Four slices for the two channels together, against
//  72 free - comfortable.
//---------------------------------------------------------------------------------
reg signed [DW+COEFW:0] prod;

always @(posedge clk_i) prod <= pair * coef_p;

//---------------------------------------------------------------------------------
//  Stage 4 - accumulate
//
//  `vld` carries the "this tap is real" flag down the pipeline alongside the
//  data, so the accumulator only adds cycles that correspond to an actual tap
//  and ignores the pipeline filling and draining.
//---------------------------------------------------------------------------------
reg [2:0] vld;
always @(posedge clk_i) begin
  if (rstn_i == 1'b0) vld <= 3'b0;
  else                vld <= {vld[1:0], issue};
end

reg signed [ACCW-1:0] acc;

always @(posedge clk_i) begin
  if (rstn_i == 1'b0)   acc <= {ACCW{1'b0}};
  else if (stb_i)       acc <= {ACCW{1'b0}};   // clear at the start of a pass
  else if (vld[2])      acc <= acc + prod;     // vld[2] marks a valid product
end

//---------------------------------------------------------------------------------
//  Output
//
//  The pass is finished four cycles after the last tap is fetched: three to
//  travel down the pipeline plus one for the accumulator to settle.
//
//  Dividing by 2^COEF_FRAC undoes the coefficient scaling. Because the
//  coefficients sum to exactly 2^COEF_FRAC, a constant in gives the same
//  constant out - switching correction on and off does not change the scale.
//
//  Saturation matters here: the correction BOOSTS the band edge by up to
//  2.27 dB, so a signal already near full scale could overflow. Saturating
//  clips it to the largest representable value, which is visible and sane;
//  letting it wrap would turn a large positive number into a large negative one
//  and produce a spike that looks like real physics.
//---------------------------------------------------------------------------------
reg [3:0] done_pipe;
always @(posedge clk_i) begin
  if (rstn_i == 1'b0) done_pipe <= 4'b0;
  else                done_pipe <= {done_pipe[2:0], last_tap};
end

wire signed [ACCW-COEF_FRAC-1:0] scaled = acc >>> COEF_FRAC;

localparam signed [DW-1:0] SAT_MAX =  {1'b0, {(DW-1){1'b1}}};   // +2^31 - 1
localparam signed [DW-1:0] SAT_MIN =  {1'b1, {(DW-1){1'b0}}};   // -2^31

always @(posedge clk_i) begin
  if (rstn_i == 1'b0) begin
    dat_o <= {DW{1'b0}};
    stb_o <= 1'b0;
  end else begin
    stb_o <= done_pipe[3];
    if (done_pipe[3]) begin
      if      (scaled >  SAT_MAX) dat_o <= SAT_MAX;
      else if (scaled <  SAT_MIN) dat_o <= SAT_MIN;
      else                        dat_o <= scaled[DW-1:0];
    end
  end
end

endmodule
