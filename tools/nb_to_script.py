#!/usr/bin/env python3
"""
Turn a Jupyter notebook into a plain Python script that runs anywhere.

WHY THIS EXISTS
---------------
The test notebooks have to RUN on the Red Pitaya, because they read the chip's
registers through /dev/mem and that file only exists on the board. But they do
not have to be OPERATED from the board's web page. A notebook is just a text
file; the browser is only one way of pressing play.

This flattens one into a script, so it can be run over an SSH connection with no
browser, no Jupyter server, and no clicking. Everything it prints goes to one
log file, which can then be copied back to the PC and read - by you, or by
anyone helping you.

WHAT IT DOES WITH PLOTS
-----------------------
A script has no screen to draw on, so matplotlib is switched to a file backend
and every plt.show() is turned into "save this figure as a PNG next to the log".
Nothing is lost; the pictures just arrive as files.

USE
---
    python3 nb_to_script.py "Test Stage 5 - Droop Correction.ipynb"
    python3 nb_to_script.py <notebook> -o out.py

Normally you do not call this yourself - run_on_board.ps1 does it for you.
"""

import argparse
import json
import os
import re
import sys

PREAMBLE = '''# ---------------------------------------------------------------------------
#  GENERATED by tools/nb_to_script.py - do not edit, edit the notebook instead
#  Source notebook : {src}
# ---------------------------------------------------------------------------
import sys as _sys, time as _time
_RUN = "{run}"
print("=" * 72)
print(" %s" % _RUN)
print(" started %s" % _time.strftime("%Y-%m-%d %H:%M:%S"))
print("=" * 72)

# No screen here, so draw to files instead. Any plt.show() becomes a PNG saved
# next to the log, numbered in the order the notebook produces them.
try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as _plt
    _fign = [0]

    def _show_to_file(*a, **k):
        _fign[0] += 1
        name = "%s_fig%02d.png" % (_RUN, _fign[0])
        _plt.savefig(name, dpi=110, bbox_inches="tight")
        _plt.close("all")
        print("[figure saved: %s]" % name)

    _plt.show = _show_to_file
except ImportError:
    pass

'''

CELL_HEADER = '''
# ===========================================================================
print("")
print("--- cell {n} " + "-" * 55)
# ===========================================================================
'''

EPILOGUE = '''
print("")
print("=" * 72)
print(" finished %s" % _time.strftime("%Y-%m-%d %H:%M:%S"))
print("=" * 72)
'''


#  A magic (%matplotlib, !ls) is a notebook-only instruction and has to go. The
#  trap is that % is also Python's formatting operator, and a wrapped call like
#
#      print('%d of %d'
#            % (a, b))
#
#  has a continuation line whose first character is %. Blanking that produces a
#  file that looks fine and will not compile. So a line only counts as a magic
#  if no bracket is still open above it AND the % or ! is followed by a letter
#  (a format continuation is followed by a space or an opening bracket).
MAGIC = re.compile(r'^\s*(%{1,2}[A-Za-z]|![A-Za-z./])')


def strip_magics(body):
    out, depth, cont = [], 0, False
    for ln in body.split('\n'):
        if depth == 0 and not cont and MAGIC.match(ln):
            out.append('')
        else:
            out.append(ln)
        code = re.sub(r'(\'\'\'|""")(.*?)\1|\'[^\']*\'|"[^"]*"|#.*', '', ln)
        depth = max(0, depth + sum(code.count(c) for c in '([{')
                              - sum(code.count(c) for c in ')]}'))
        cont = ln.rstrip().endswith('\\')
    return '\n'.join(out)


def flatten(nb_path, out_path=None):
    with open(nb_path, 'r', encoding='utf-8') as fh:
        nb = json.load(fh)

    run = re.sub(r'[^A-Za-z0-9]+', '_', os.path.splitext(os.path.basename(nb_path))[0]).strip('_')
    if out_path is None:
        out_path = run + '.py'

    parts = [PREAMBLE.format(src=os.path.basename(nb_path), run=run)]
    n = 0
    for cell in nb['cells']:
        if cell.get('cell_type') != 'code':
            continue
        body = ''.join(cell['source'])
        if not body.strip():
            continue
        body = strip_magics(body)
        parts.append(CELL_HEADER.format(n=n))
        parts.append(body.rstrip() + '\n')
        n += 1
    parts.append(EPILOGUE)

    with open(out_path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(parts))
    return out_path, n


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('notebook')
    ap.add_argument('-o', '--output', default=None)
    args = ap.parse_args()

    if not os.path.exists(args.notebook):
        sys.exit('not found: %s' % args.notebook)
    out, n = flatten(args.notebook, args.output)
    print('wrote %s  (%d code cells)' % (out, n))
